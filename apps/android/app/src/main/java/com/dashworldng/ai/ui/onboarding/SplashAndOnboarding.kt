/**
 * The brand moment after the system splash ("Intelligence. Possibility. Arrival."): always dark and
 * cinematic, whatever the theme. The scene layers (planet, terrain, figure) are generated by
 * tools/brand/splash_scene.py and shared with the web; the mark, wordmark, tagline and footer are
 * drawn here. No buttons, no feature cards. About 1.6 s; shorter and still with reduced motion.
 */
@Composable
fun SplashScreen(onFinished: () -> Unit) {
    SplashContent(reducedMotion = rememberReducedMotion(), onFinished = onFinished)
}

@Composable
fun SplashContent(reducedMotion: Boolean, onFinished: () -> Unit) {
    val c = DashTheme.colors
    val reveal = remember { Animatable(if (reducedMotion) 1f else 0f) }
    LaunchedEffect(Unit) {
        if (reducedMotion) {
            delay(400)
        } else {
            launch { reveal.animateTo(1f, tween(durationMillis = 1100, easing = FastOutSlowInEasing)) }
            delay(1600)
        }
        onFinished()
    }
    BoxWithConstraints(
        Modifier
            .fillMaxSize()
            .background(Brush.verticalGradient(listOf(Color(0xFF0D0D0C), c.brandCanvas, Color(0xFF1C1B19))))
            .testTag("splash")
            .semantics(mergeDescendants = true) { contentDescription = "DASH AI. Beyond the Digital. A Dash World product." },
    ) {
        val w = maxWidth
        val h = maxHeight
        val planet = maxOf(h * 0.84f, w * 0.56f)
        Image(
            painterResource(R.drawable.splash_planet),
            contentDescription = null,
            modifier = Modifier
                .requiredSize(planet)
                .offset(x = w * 0.8f - planet / 2, y = h * 0.31f - planet / 2)
                .graphicsLayer { alpha = reveal.value },
        )
        Image(
            painterResource(R.drawable.splash_terrain),
            contentDescription = null,
            contentScale = ContentScale.FillBounds,
            modifier = Modifier.align(Alignment.BottomCenter).fillMaxWidth().height(h * 0.44f),
        )
        Image(
            painterResource(R.drawable.splash_figure),
            contentDescription = null,
            modifier = Modifier
                .align(Alignment.BottomCenter)
                .padding(bottom = h * 0.072f)
                .height(h * 0.034f)
                .width(h * 0.017f)
                .graphicsLayer { alpha = reveal.value },
        )
        Column(
            horizontalAlignment = Alignment.CenterHorizontally,
            modifier = Modifier
                .fillMaxWidth()
                .padding(top = h * 0.24f)
                .graphicsLayer {
                    alpha = reveal.value
                    translationY = (1f - reveal.value) * 10.dp.toPx()
                },
        ) {
            val markSize = (h * 0.17f).coerceIn(84.dp, 168.dp)
            Box(contentAlignment = Alignment.Center) {
                // Soft champagne light around the mark.
                Box(
                    Modifier
                        .size(markSize * 1.6f)
                        .background(Brush.radialGradient(listOf(Color(0x59DCC07F), Color(0x1FC9A75B), Color.Transparent))),
                )
                BrandMark(size = markSize, luminous = true)
            }
            Spacer(Modifier.height(h * 0.03f))
            Text(
                "DASH AI",
                style = TextStyle(
                    brush = Brush.verticalGradient(listOf(Color(0xFFFAF8F3), Color(0xFFF4ECD9), Color(0xFFDCC07F))),
                    fontFamily = BrandSerif,
                    fontSize = (h.value * 0.052f).coerceIn(28f, 52f).sp,
                    letterSpacing = 0.26.em,
                ),
            )
            Spacer(Modifier.height(h * 0.016f))
            Text(
                "Beyond the Digital.",
                style = TextStyle(
                    fontFamily = BrandSerif,
                    fontStyle = FontStyle.Italic,
                    fontSize = (h.value * 0.024f).coerceIn(15f, 22f).sp,
                    letterSpacing = 0.12.em,
                    color = Color(0xFFF4ECD9).copy(alpha = 0.86f),
                ),
            )
        }
        Text(
            "—   A DASH WORLD PRODUCT   —",
            style = TextStyle(fontSize = 11.sp, letterSpacing = 0.32.em, color = Color(0xFF57534B), textAlign = TextAlign.Center),
            modifier = Modifier.align(Alignment.BottomCenter).navigationBarsPadding().padding(bottom = h * 0.032f),
        )
    }
}

private data class Cue(val icon: ImageVector, val title: String, val text: String)

private val cues = listOf(
    Cue(Icons.Rounded.Bolt, "Get answers faster", "Ask in your own words and get clear, structured answers."),
    Cue(Icons.Rounded.Layers, "Go deeper with context", "Add your documents and pick a focused mode for each chat."),
    Cue(Icons.Rounded.AutoAwesome, "Turn ideas into action", "Draft, plan and analyse in focused modes built for real work."),
)

/** One calm screen for first launch. Returning users never see it again. */
@Composable
fun OnboardingScreen(onFinish: () -> Unit) {
    val c = DashTheme.colors
    Box(Modifier.fillMaxSize().background(c.background).testTag("onboarding")) {
        ContentWidth(Modifier.fillMaxSize(), maxWidth = Sizing.maxFormWidth) {
            Column(
                Modifier
                    .fillMaxSize()
                    .statusBarsPadding()
                    .navigationBarsPadding()
                    .verticalScroll(rememberScrollState())
                    .padding(horizontal = Spacing.xl, vertical = Spacing.xl),
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    BrandMark(size = 26.dp)
                    Spacer(Modifier.width(Spacing.sm))
                    BrandWordmark(fontSize = 14.sp)
                }
                Spacer(Modifier.height(Spacing.xxxl))
                Text(
                    "What are we building today?",
                    style = MaterialTheme.typography.displaySmall,
                    color = c.ink,
                    modifier = Modifier.semantics { heading() }.testTag("onboarding_title"),
                )
                Spacer(Modifier.height(Spacing.md))
                Text(
                    "DASH AI helps you think, create, analyse and act.",
                    style = MaterialTheme.typography.bodyLarge,
                    color = c.inkSecondary,
                )
                Spacer(Modifier.height(Spacing.xxl))
                Column(verticalArrangement = Arrangement.spacedBy(Spacing.xl)) {
                    cues.forEach { cue -> CueRow(cue) }
                }
                Spacer(Modifier.weight(1f).height(Spacing.xxl))
                PrimaryButton(
                    "Get started",
                    onClick = onFinish,
                    modifier = Modifier.fillMaxWidth().padding(top = Spacing.xxl).testTag("onboarding_start"),
                )
                Spacer(Modifier.height(Spacing.md))
                Text(
                    "A Dash World product",
                    style = MaterialTheme.typography.labelSmall,
                    color = c.inkTertiary,
                    textAlign = TextAlign.Center,
                    modifier = Modifier.fillMaxWidth(),
                )
            }
        }
    }
}

@Composable
private fun CueRow(cue: Cue) {
    val c = DashTheme.colors
    Row(verticalAlignment = Alignment.Top, modifier = Modifier.semantics(mergeDescendants = true) {}) {
        Box(Modifier.size(40.dp).clip(CircleShape).background(c.accentContainer), contentAlignment = Alignment.Center) {
            Icon(cue.icon, contentDescription = null, tint = c.accentInk, modifier = Modifier.size(Sizing.icon))
        }
        Spacer(Modifier.width(Spacing.lg))
        Column {
            Text(cue.title, style = MaterialTheme.typography.titleMedium, color = c.ink)
            Spacer(Modifier.height(Spacing.xxs))
            Text(cue.text, style = MaterialTheme.typography.bodyMedium, color = c.inkSecondary)
        }
    }
}
