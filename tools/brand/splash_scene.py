#!/usr/bin/env python3
"""
The DASH AI splash scene ("Intelligence. Possibility. Arrival."), written once and emitted for both
platforms: SVG for the web (apps/web/src/brand/splash/) and VectorDrawable for Android
(apps/android/app/src/main/res/drawable/splash_*.xml). Run from the repository root:

    python3 tools/brand/splash_scene.py

Three layers, composed by each app with the mark, wordmark, tagline and footer drawn in code:
  planet  - a vast dark world with a warm lit rim, anchored top-right
  terrain - abstract flowing ridges with fine luminous contour lines (data, not sand) opening onto
            a luminous ivory horizon; stretched to the screen width
  figure  - one tiny anonymous person looking up, placed on the horizon
Only the approved palette is used (docs/ui-design-system.md). Do not edit the outputs by hand.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "apps/web/src/brand/splash"
AND = ROOT / "apps/android/app/src/main/res/drawable"
HEADER = "Generated by tools/brand/splash_scene.py. Do not edit by hand."


def hexa(color, alpha=1.0):
    """#RRGGBB + alpha -> (svg colour, svg opacity, android #AARRGGBB)."""
    a = max(0, min(255, round(alpha * 255)))
    return color, alpha, f"#{a:02X}{color[1:].upper()}"


class Lin:
    def __init__(self, x1, y1, x2, y2, stops):
        self.k, self.c, self.stops = "linear", (x1, y1, x2, y2), stops


class Rad:
    def __init__(self, cx, cy, r, stops):
        self.k, self.c, self.stops = "radial", (cx, cy, r), stops


class Shape:
    def __init__(self, d, fill=None, stroke=None, width=0.0, alpha=1.0):
        self.d, self.fill, self.stroke, self.width, self.alpha = d, fill, stroke, width, alpha


class Layer:
    def __init__(self, name, w, h, shapes, clip=None, clipped=(), stretch=False):
        self.name, self.w, self.h, self.shapes, self.clip, self.clipped = name, w, h, shapes, clip, clipped
        # Stretch layers fill any screen shape; the others keep their proportions.
        self.stretch = stretch


# ---- emitters -------------------------------------------------------------------------------------

def svg(layer):
    defs, body, n = [], [], [0]

    def paint(p):
        if isinstance(p, str):
            return p
        n[0] += 1
        gid = f"g{n[0]}"
        stops = "".join(f'<stop offset="{o}" stop-color="{hexa(c, a)[0]}" stop-opacity="{a:g}"/>' for o, c, a in p.stops)
        if p.k == "linear":
            x1, y1, x2, y2 = p.c
            defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{stops}</linearGradient>')
        else:
            cx, cy, r = p.c
            defs.append(f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{cx}" cy="{cy}" r="{r}">{stops}</radialGradient>')
        return f"url(#{gid})"

    def shape(s):
        attrs = [f'd="{s.d}"']
        attrs.append(f'fill="{paint(s.fill)}"' if s.fill else 'fill="none"')
        if s.stroke:
            attrs.append(f'stroke="{paint(s.stroke)}" stroke-width="{s.width}" stroke-linecap="round"')
        if s.alpha != 1:
            attrs.append(f'opacity="{s.alpha:g}"')
        return f"<path {' '.join(attrs)}/>"

    body = [shape(s) for s in layer.shapes]
    if layer.clip:
        defs.append(f'<clipPath id="clip"><path d="{layer.clip}"/></clipPath>')
        body.append('<g clip-path="url(#clip)">' + "".join(shape(s) for s in layer.clipped) + "</g>")
    aspect = ' preserveAspectRatio="none"' if layer.stretch else ""
    return (f'<!-- {HEADER} -->\n<svg xmlns="http://www.w3.org/2000/svg" width="{layer.w}" height="{layer.h}" '
            f'viewBox="0 0 {layer.w} {layer.h}"{aspect}><defs>{"".join(defs)}</defs>{"".join(body)}</svg>\n')


def vector(layer):
    def grad(p, attr):
        items = "".join(f'<item android:offset="{o}" android:color="{hexa(c, a)[2]}"/>' for o, c, a in p.stops)
        if p.k == "linear":
            x1, y1, x2, y2 = p.c
            g = f'<gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">'
        else:
            cx, cy, r = p.c
            g = f'<gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}">'
        return f'<aapt:attr name="android:{attr}">{g}{items}</gradient></aapt:attr>'

    def shape(s):
        attrs, inner = [f'android:pathData="{s.d}"'], []
        if s.fill:
            if isinstance(s.fill, str):
                attrs.append(f'android:fillColor="{hexa(s.fill)[2]}"')
            else:
                inner.append(grad(s.fill, "fillColor"))
            if s.alpha != 1:
                attrs.append(f'android:fillAlpha="{s.alpha:g}"')
        if s.stroke:
            attrs.append(f'android:strokeWidth="{s.width}" android:strokeLineCap="round"')
            if isinstance(s.stroke, str):
                attrs.append(f'android:strokeColor="{hexa(s.stroke)[2]}"')
            else:
                inner.append(grad(s.stroke, "strokeColor"))
            if s.alpha != 1:
                attrs.append(f'android:strokeAlpha="{s.alpha:g}"')
        a = " ".join(attrs)
        return f"<path {a}>{''.join(inner)}</path>" if inner else f"<path {a}/>"

    body = [shape(s) for s in layer.shapes]
    if layer.clip:
        body.append(f'<group><clip-path android:pathData="{layer.clip}"/>' + "".join(shape(s) for s in layer.clipped) + "</group>")
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {HEADER} -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" '
            f'android:width="{layer.w}dp" android:height="{layer.h}dp" android:viewportWidth="{layer.w}" android:viewportHeight="{layer.h}">'
            + "".join(body) + "</vector>\n")


# ---- palette --------------------------------------------------------------------------------------

GRAPHITE, CHARCOAL, INK = "#141413", "#1C1B19", "#1D1C1A"
CHAMPAGNE, DEEP_CHAMPAGNE, LIGHT_CHAMPAGNE = "#C9A75B", "#7A5C1C", "#DCC07F"
IVORY, NUDE, CREAM = "#FAF8F3", "#F4ECD9", "#F4F1EA"


def circle(cx, cy, r):
    return f"M{cx - r},{cy} A{r},{r} 0 1,1 {cx + r},{cy} A{r},{r} 0 1,1 {cx - r},{cy} Z"


# ---- planet ---------------------------------------------------------------------------------------

def planet():
    c, r = 200, 190
    # Lit from the upper right, like the reference: warm surface light fading into shadow.
    disc = Rad(318, 66, 300, [(0, "#7A6544", 1), (0.18, "#4E412D", 1), (0.42, "#2A251E", 1), (0.7, "#171614", 1), (1, "#121211", 1)])
    rim = Lin(372, 30, 60, 300, [(0, IVORY, 1), (0.25, NUDE, 0.85), (0.55, LIGHT_CHAMPAGNE, 0.35), (0.85, CHAMPAGNE, 0.06), (1, CHAMPAGNE, 0)])
    halo = Lin(372, 30, 90, 300, [(0, LIGHT_CHAMPAGNE, 0.55), (0.45, CHAMPAGNE, 0.12), (1, CHAMPAGNE, 0)])
    bands = []
    # Cloud and surface bands, brightest where the light falls.
    for i, (y, amp, a) in enumerate([(40, 10, 0.34), (66, 14, 0.3), (92, 12, 0.26), (120, 16, 0.2), (150, 12, 0.15), (182, 14, 0.1), (214, 10, 0.07)]):
        x0 = 150 + i * 6
        bands.append(Shape(f"M{x0},{y} C{x0 + 50},{y - amp} {x0 + 110},{y + amp} {x0 + 160},{y - amp / 2} S{x0 + 220},{y + amp} {x0 + 280},{y}",
                           stroke=NUDE, width=3.2, alpha=a * 0.32))
        bands.append(Shape(f"M{x0 + 30},{y + 9} C{x0 + 80},{y + 9 - amp / 2} {x0 + 140},{y + 9 + amp / 2} {x0 + 250},{y + 6}",
                           stroke=LIGHT_CHAMPAGNE, width=0.5, alpha=a * 0.35))
    return Layer("planet", 400, 400, [
        Shape(circle(c, c, r + 5), stroke=halo, width=12),
        Shape(circle(c, c, r), fill=disc),
        Shape(circle(c, c, r), stroke=rim, width=2.6),
    ], clip=circle(c, c, r - 1), clipped=bands)


# ---- terrain and horizon --------------------------------------------------------------------------

def _smooth(points):
    """Catmull-Rom through the points, as cubic Beziers (one smooth flowing line)."""
    f = lambda v: f"{v:.1f}".rstrip("0").rstrip(".")
    d = [f"M{f(points[0][0])},{f(points[0][1])}"]
    for i in range(len(points) - 1):
        p0, p1, p2 = points[max(i - 1, 0)], points[i], points[i + 1]
        p3 = points[min(i + 2, len(points) - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f"C{f(c1[0])},{f(c1[1])} {f(c2[0])},{f(c2[1])} {f(p2[0])},{f(p2[1])}")
    return " ".join(d)


def _ridge(base, waves, valley, dy=0.0):
    """A ridge line: layered long waves, dipping gently where the valley opens onto the light."""
    pts = []
    for i in range(41):
        x = -20 + i * 11
        y = base + dy
        for amp, length, phase in waves:
            y += amp * math.sin(2 * math.pi * x / length + phase)
        y += valley * math.exp(-((x - 200) / 70) ** 2)
        pts.append((x, y))
    return pts


def terrain():
    W, H = 400, 320
    sky_haze = Lin(0, 60, 0, 270, [(0, CHAMPAGNE, 0), (0.6, CHAMPAGNE, 0.14), (1, NUDE, 0.5)])
    glow = Rad(200, 334, 250, [(0, IVORY, 1), (0.36, CREAM, 1), (0.6, NUDE, 1), (0.82, LIGHT_CHAMPAGNE, 0.9), (1, CHAMPAGNE, 0.0)])
    bloom = Rad(200, 262, 150, [(0, IVORY, 0.85), (0.3, NUDE, 0.45), (1, NUDE, 0)])
    shapes = [Shape(f"M0,60 L{W},60 L{W},{H} L0,{H} Z", fill=sky_haze), Shape(f"M0,110 L{W},110 L{W},{H} L0,{H} Z", fill=bloom)]
    # Back to front. Long, slow waves, not dunes: each crest carries fine luminous contour lines,
    # like a field of data seen from far away.
    ridges = [
        (150, [(7, 260, 0.4), (3, 97, 1.9)], 16, "#6A573A", 0.5, 4),
        (178, [(9, 300, 2.2), (3.5, 120, 0.3)], 22, "#473C2C", 0.72, 4),
        (208, [(10, 340, 4.0), (4, 140, 2.6)], 30, "#2E2820", 0.88, 3),
        (240, [(9, 380, 1.1), (3, 150, 4.4)], 34, CHARCOAL, 1, 3),
    ]
    for base, waves, valley, top, alpha, lines in ridges:
        crest = _ridge(base, waves, valley)
        d = _smooth(crest)
        body = Lin(0, base - 30, 0, H, [(0, top, alpha), (0.5, GRAPHITE, alpha), (1, GRAPHITE, alpha)])
        shapes.append(Shape(f"{d} L420,{H} L-20,{H} Z", fill=body))
        shapes.append(Shape(d, stroke=Lin(0, 0, W, 0, [(0, LIGHT_CHAMPAGNE, 0.12), (0.5, NUDE, 0.8), (1, LIGHT_CHAMPAGNE, 0.12)]), width=0.7))
        for k in range(1, lines + 1):
            shapes.append(Shape(_smooth(_ridge(base, waves, valley * (1 - 0.08 * k), dy=3.2 * k)), stroke=LIGHT_CHAMPAGNE, width=0.3, alpha=0.4 / k))
    # The luminous horizon the figure walks towards.
    shapes.append(Shape("M-60,330 C40,266 140,254 200,254 C260,254 360,266 460,330 Z", fill=glow))
    shapes.append(Shape("M-20,302 C70,266 150,258 200,258 C250,258 330,266 420,302", stroke=IVORY, width=0.5, alpha=0.6))
    return Layer("terrain", W, H, shapes, stretch=True)


def _shift(token, dy):
    """Moves every y coordinate in an SVG path token down by dy."""
    head = token[0] if token[0].isalpha() else ""
    rest = token[len(head):]
    if "," not in rest:
        return token
    x, y = rest.split(",")
    return f"{head}{x},{float(y) + dy:g}"


# ---- figure ---------------------------------------------------------------------------------------

def figure():
    # 20 x 40 units: a small standing person seen from behind, head tilted up, with a soft shadow.
    body = ("M8.4,9.6 C7,10.2 6.6,11.6 6.5,13.4 L6.1,21.5 C6,22.3 6.6,22.8 7.3,22.6 L7.7,31.8 C7.7,32.6 8.2,33 8.8,33 "
            "C9.4,33 9.8,32.6 9.8,31.9 L10,24.5 L10.3,31.9 C10.3,32.6 10.8,33 11.4,33 C12,33 12.4,32.6 12.4,31.8 "
            "L12.7,22.6 C13.4,22.8 14,22.3 13.9,21.5 L13.5,13.4 C13.4,11.6 13,10.2 11.6,9.6 Z")
    head = circle(10, 6.6, 2.3)
    shadow = Rad(10, 34.5, 7, [(0, INK, 0.35), (1, INK, 0)])
    return Layer("figure", 20, 40, [
        Shape("M2,34.5 C2,33.4 18,33.4 18,34.5 C18,35.6 2,35.6 2,34.5 Z", fill=shadow),
        Shape(body, fill=INK),
        Shape(head, fill=INK),
    ])


def main():
    WEB.mkdir(parents=True, exist_ok=True)
    for layer in (planet(), terrain(), figure()):
        (WEB / f"{layer.name}.svg").write_text(svg(layer))
        (AND / f"splash_{layer.name}.xml").write_text(vector(layer))
        print("wrote", layer.name)


if __name__ == "__main__":
    main()
